/**
 * General English lexical families for the local, experimental dictionary.
 *
 * Inflections below are supplied explicitly. We do not infer verb tense or part
 * of speech from a suffix. Short object/complement collocations retain syntax
 * where a bare common verb (start, make, get, take, etc.) would be ambiguous.
 * Technical terms, idioms and proper names still need human review: a finite
 * dictionary is not a semantic equivalence model or a watermark-removal tool.
 */
type Pair = readonly [string, string];
type Style = 'business' | 'academic' | 'casual';
type VerbForms = readonly [string, string, string, string];

function verbs(source: VerbForms, target: VerbForms): Pair[] {
  return source.map((word, i) => [word, target[i]] as const);
}

/** The supplied objects are ordinary noun phrases, never arbitrary templates. */
function withObjects(source: VerbForms, target: VerbForms, objects: readonly string[]): Pair[] {
  return source.flatMap((word, i) => objects.map(object => [`${word} ${object}`, `${target[i]} ${object}`] as const));
}

function withComplements(source: VerbForms, target: VerbForms, complements: readonly string[]): Pair[] {
  return withObjects(source, target, complements);
}

/** Keep one deterministic target when a shared family overlaps a style family. */
function unique(pairs: readonly Pair[]): readonly Pair[] {
  const seen = new Set<string>();
  return pairs.filter(([source, target]) => {
    if (source === target || seen.has(source)) return false;
    seen.add(source);
    return true;
  });
}

